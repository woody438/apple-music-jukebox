#!/usr/bin/env node
// One-off generator: embeds the OFL woff2 files from assets/fonts as base64
// into public/fonts.css, so the party laptop never needs a CDN. Not part of
// running the jukebox -- re-run it only if you swap a font file.
//
//   node tools/build-fonts.js
//
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'assets', 'fonts');
const OUT = path.join(ROOT, 'public', 'fonts.css');

const FACES = [
  { family: 'Monoton', weight: 400, file: 'monoton-latin-400-normal.woff2' },
  { family: 'Oswald', weight: 400, file: 'oswald-latin-400-normal.woff2' },
  { family: 'Oswald', weight: 600, file: 'oswald-latin-600-normal.woff2' },
  { family: 'Oswald', weight: 700, file: 'oswald-latin-700-normal.woff2' },
];

// Latin subset range shipped by @fontsource.
const UNICODE_RANGE =
  'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,' +
  'U+0304,U+0308,U+0329,U+2000-206F,U+2074,U+20AC,U+2122,U+2191,' +
  'U+2193,U+2212,U+2215,U+FEFF,U+FFFD';

const header = [
  '/* Generated by tools/build-fonts.js -- do not edit by hand. */',
  '/* Monoton and Oswald are licensed under the SIL Open Font License 1.1. */',
  '/* Full licence texts: assets/fonts/LICENSE-Monoton.txt, LICENSE-Oswald.txt */',
  '',
].join('\n');

const blocks = FACES.map(({ family, weight, file }) => {
  const b64 = fs.readFileSync(path.join(SRC, file)).toString('base64');
  return [
    '@font-face {',
    `  font-family: '${family}';`,
    "  font-style: normal;",
    `  font-weight: ${weight};`,
    '  font-display: block;',
    `  src: url(data:font/woff2;base64,${b64}) format('woff2');`,
    `  unicode-range: ${UNICODE_RANGE};`,
    '}',
  ].join('\n');
});

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, header + blocks.join('\n\n') + '\n');
const kb = (fs.statSync(OUT).size / 1024).toFixed(1);
console.log(`wrote ${path.relative(ROOT, OUT)} (${kb} KB, ${FACES.length} faces)`);
